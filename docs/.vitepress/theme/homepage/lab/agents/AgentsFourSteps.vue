<script setup lang="ts">
import { computed, ref } from "vue";
import HomePageInstallCommand from "../../HomePageInstallCommand.vue";
import AgentsCode from "./AgentsCode.vue";
import AgentsPage from "./AgentsPage.vue";
import { diffStats, fileName, useAgentDemo } from "./agentsDemo";

/* Concept 2, Four Steps: a Request → Change → Review → Document strip above the code and the
   page. Static copy at rest; during the demo each cell lights in turn (green done, blue in
   progress) while the code and the page do the work. The four reasons are folded into the step
   descriptions, so there is no second strip. The play control lives in the window header. */

const root = ref<HTMLElement | null>(null);
const demo = useAgentDemo({ root, autoplayDelay: 4000 });

const phase = demo.phase;
const step1Done = computed(() => phase.value !== "rest" && phase.value !== "typing");
const step2Active = computed(() => phase.value === "proposing");
const step2Done = computed(() => demo.proposed.value);
const step3Done = computed(() => demo.reviewed.value);
const step4Done = computed(() => demo.after.value);
</script>

<template>
  <section class="content">
    <div ref="root" class="panel fs-panel">
      <div class="panel-head">
        <div class="lead">
          <h2 class="card-title">From a request to an updated document in four steps</h2>
        </div>
        <home-page-install-command />
      </div>

      <ol class="steps" aria-label="The loop">
        <li class="step" :class="{ done: step1Done }">
          <div class="step-num label">
            <i v-if="step1Done" class="fa-regular fa-circle-check" aria-hidden="true"></i><span v-else>1</span> Request
          </div>
          <h3 class="row-title step-title">Plain language, from anyone</h3>
          <p v-if="phase === 'rest'" class="row-description step-text">A product owner asks for a change the way they always have.</p>
          <p v-else class="row-description step-text"><q>{{ demo.promptText.value }}</q><span v-if="phase === 'typing'" class="caret"></span></p>
        </li>

        <li class="step" :class="{ active: step2Active, done: step2Done }">
          <div class="step-num label">
            <i v-if="step2Active" class="fa-regular fa-circle-notch fa-spin" aria-hidden="true"></i>
            <i v-else-if="step2Done" class="fa-regular fa-circle-check" aria-hidden="true"></i>
            <span v-else>2</span> Change
          </div>
          <h3 class="row-title step-title">A small diff from your agent</h3>
          <p v-if="!step2Active && !step2Done" class="row-description step-text">Documents are code, so the change is a few typed lines the compiler checks.</p>
          <p v-else-if="step2Active" class="row-description step-text">Editing <code>{{ fileName }}</code></p>
          <p v-else class="row-description step-text"><span class="minus">−{{ diffStats.removed }}</span> <span class="plus">+{{ diffStats.added }}</span> lines in <code>{{ fileName }}</code>, compiles.</p>
        </li>

        <li class="step" :class="{ done: step3Done }">
          <div class="step-num label">
            <i v-if="step3Done" class="fa-regular fa-circle-check" aria-hidden="true"></i><span v-else>3</span> Review
          </div>
          <h3 class="row-title step-title">Reviewed by you</h3>
          <p v-if="!step3Done" class="row-description step-text">The diff goes through the same pull request and history as the rest of the project.</p>
          <p v-else class="row-description step-text">Reviewed and merged by you.</p>
        </li>

        <li class="step" :class="{ done: step4Done }">
          <div class="step-num label">
            <i v-if="step4Done" class="fa-regular fa-circle-check" aria-hidden="true"></i><span v-else>4</span> Document
          </div>
          <h3 class="row-title step-title">Rendered again</h3>
          <p v-if="!step4Done" class="row-description step-text">The PDF is generated by your build; the Companion App shows it as you save.</p>
          <p v-else class="row-description step-text"><code>invoice.pdf</code> rendered with the credit line in red.</p>
        </li>
      </ol>

      <div class="fs-body">
        <agents-code :lines="demo.lines.value">
          <template #meta>
            <button v-if="phase === 'rest'" type="button" class="action small" @click="demo.play()">
              <i class="fa-regular fa-play" aria-hidden="true"></i> Play the request <span class="meta">15 s</span>
            </button>
            <button v-else-if="phase === 'done'" type="button" class="action small" @click="demo.play()">
              <i class="fa-regular fa-rotate-right" aria-hidden="true"></i> Replay
            </button>
            <template v-else-if="phase === 'reviewed'">main</template>
            <template v-else-if="phase !== 'typing'">proposed change</template>
          </template>
        </agents-code>

        <div class="side">
          <agents-page :after="demo.after.value" :width="320" />
        </div>
      </div>
    </div>
  </section>
</template>

